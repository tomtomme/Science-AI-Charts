/**
 * Returns the localized storyline for a model based on the active language.
 * If the user updates the Google Sheet with a custom or bilingual string, it respects it dynamically.
 */
export function translateStoryline(raw: string | undefined, lang: 'de' | 'en'): string {
  if (!raw) return '';
  const trimmed = raw.trim();
  if (!trimmed) return '';

  // Direct case-insensitive match against translation dictionary
  const lower = trimmed.toLowerCase();
  for (const [key, trans] of Object.entries(STORYLINE_TRANSLATIONS)) {
    if (key.toLowerCase() === lower) {
      return lang === 'de' ? trans.de : trans.en;
    }
  }

  // Handle explicit bilingual separator: e.g. "DE Text / EN Text" or "DE Text // EN Text"
  if (trimmed.includes(' // ') || trimmed.includes(' / ')) {
    const parts = trimmed.split(/\s*\/\/?\s*/);
    if (parts.length >= 2) {
      return lang === 'de' ? parts[0].trim() : parts[1].trim();
    }
  }

  // Fallback directly to the live Google Sheet string
  return trimmed;
}
